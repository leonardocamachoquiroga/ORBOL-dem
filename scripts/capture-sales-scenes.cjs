const {chromium}=require(process.env.OLBOL_RUNTIME_MODULES+'/playwright');
(async()=>{
  const browser=await chromium.launch({channel:'msedge',headless:true});
  const page=await browser.newPage({viewport:{width:1440,height:1000}});
  await page.emulateMedia({reducedMotion:'reduce'});
  await page.route('**/api/advisor',route=>route.abort());
  await page.goto('http://localhost:3000/vehiculos',{waitUntil:'networkidle'});
  await page.locator('.catalog-layout').evaluate(element=>scrollTo({top:element.getBoundingClientRect().top+scrollY-110,behavior:'instant'}));
  await page.screenshot({path:'docs/capturas/catalogo-escena.png'});
  await page.goto('http://localhost:3000/asesor',{waitUntil:'networkidle'});
  await page.locator('.message').first().waitFor();
  const send=async text=>{await page.getByRole('textbox',{name:'Mensaje para el asesor'}).fill(text);await page.getByRole('button',{name:'Enviar mensaje'}).click();await page.waitForFunction(()=>!document.querySelector('.advisor-composer input').disabled);};
  await send('Somos 5, viajamos los fines de semana y tengo un presupuesto de USD 30 mil');
  await page.screenshot({path:'docs/capturas/recomendacion-escena.png'});
  await send('Quiero cotizar');
  await page.getByRole('button',{name:'Preparar continuidad'}).click();
  await page.locator('.whatsapp-card__message').waitFor();
  const q=await page.locator('.quote-panel').boundingBox();
  const w=await page.locator('.whatsapp-card').boundingBox();
  await page.screenshot({path:'docs/capturas/cotizacion-escena.png',clip:{x:q.x,y:q.y,width:q.width,height:w.y+w.height-q.y}});
  await send('Me interesa');
  await page.goto('http://localhost:3000/crm',{waitUntil:'networkidle'});
  await page.locator('.crm-board').waitFor();
  await page.locator('.crm-metrics').evaluate(element=>scrollTo({top:element.getBoundingClientRect().top+scrollY-110,behavior:'instant'}));
  await page.screenshot({path:'docs/capturas/crm-escena.png'});
  await page.goto('http://localhost:3000/demo#solucion',{waitUntil:'networkidle'});
  await page.screenshot({path:'docs/capturas/solucion-escena.png'});
  console.log('Escenas comerciales capturadas');
  await browser.close();
})().catch(e=>{console.error(e);process.exit(1)});
